"""Shared setup: seeding, data split, metrics. Every model imports from here
so they all see the exact same data and evaluation."""
import random
import time

import numpy as np
import torch
from torch.utils.data import ConcatDataset, DataLoader, random_split
from torchvision import datasets, transforms

SEED = 42
BATCH_SIZE = 128
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


def set_seed(seed=SEED):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def get_loaders(root="data", batch_size=BATCH_SIZE):
    """Fashion-MNIST, all 70k images merged then split 80/10/10 with a fixed seed.
    Pixels are in [0, 1]. GAN/DDPM rescale to [-1, 1] themselves."""
    tf = transforms.ToTensor()
    full = ConcatDataset([
        datasets.FashionMNIST(root, train=True, download=True, transform=tf),
        datasets.FashionMNIST(root, train=False, download=True, transform=tf),
    ])
    n = len(full)
    n_train, n_val = int(0.8 * n), int(0.1 * n)
    train, val, test = random_split(
        full, [n_train, n_val, n - n_train - n_val],
        generator=torch.Generator().manual_seed(SEED),
    )
    return (
        DataLoader(train, batch_size, shuffle=True, num_workers=2, pin_memory=True),
        DataLoader(val, batch_size, shuffle=False, num_workers=2),
        DataLoader(test, batch_size, shuffle=False, num_workers=2),
    )


# ---------- metrics (all expect images in [0, 1]) ----------

def mse_psnr_ssim(x, x_hat):
    """Mean MSE, PSNR (dB), SSIM over a batch."""
    from torchmetrics.functional.image import structural_similarity_index_measure as ssim
    x_hat = x_hat.clamp(0, 1)
    mse_per_img = ((x - x_hat) ** 2).flatten(1).mean(1)
    psnr = (10 * torch.log10(1.0 / mse_per_img.clamp_min(1e-10))).mean()
    return mse_per_img.mean().item(), psnr.item(), ssim(x_hat, x, data_range=1.0).item()


@torch.no_grad()
def eval_reconstruction(recon_fn, test_loader):
    """recon_fn: batch of images -> reconstructed images. Averages over the test set."""
    totals, n = np.zeros(3), 0
    for x, _ in test_loader:
        x = x.to(DEVICE)
        totals += np.array(mse_psnr_ssim(x, recon_fn(x))) * len(x)
        n += len(x)
    mse, psnr, ssim = totals / n
    return {"mse": mse, "psnr": psnr, "ssim": ssim}


@torch.no_grad()
def fid_score(sample_fn, test_loader, n_samples=7000, batch=50):
    """FID between the 7000 real test images and n_samples generated by sample_fn(batch) -> [B,1,28,28] in [0,1].
    Grayscale is repeated to 3 channels; torchmetrics resizes to Inception's 299x299.
    Small batches because 299x299 Inception activations don't fit a 4GB GPU at batch 128."""
    from torchmetrics.image.fid import FrechetInceptionDistance
    fid = FrechetInceptionDistance(feature=2048, normalize=True).to(DEVICE)
    for x, _ in test_loader:
        for chunk in x.split(batch):
            fid.update(chunk.to(DEVICE).repeat(1, 3, 1, 1), real=True)
    done = 0
    while done < n_samples:
        fake = sample_fn(batch).clamp(0, 1)
        fid.update(fake.repeat(1, 3, 1, 1), real=False)
        done += batch
    return fid.compute().item()


@torch.no_grad()
def latency_ms(sample_fn, batch=64, warmup=3, runs=10):
    """Average wall-clock ms to generate one batch of 64 images."""
    for _ in range(warmup):
        sample_fn(batch)
    if DEVICE.type == "cuda":
        torch.cuda.synchronize()
    t0 = time.perf_counter()
    for _ in range(runs):
        sample_fn(batch)
    if DEVICE.type == "cuda":
        torch.cuda.synchronize()
    return (time.perf_counter() - t0) / runs * 1000


if __name__ == "__main__":
    # sanity check: split sizes, pixel range, metrics on identical/noisy images
    set_seed()
    tr, va, te = get_loaders()
    sizes = [len(l.dataset) for l in (tr, va, te)]
    print("split sizes:", sizes)
    assert sizes == [56000, 7000, 7000]
    x, _ = next(iter(te))
    assert 0 <= x.min() and x.max() <= 1
    mse, psnr, ssim = mse_psnr_ssim(x, x)
    assert mse == 0 and ssim > 0.99
    mse, psnr, ssim = mse_psnr_ssim(x, x + 0.1 * torch.randn_like(x))
    print(f"noisy: mse={mse:.4f} psnr={psnr:.1f}dB ssim={ssim:.3f}")
    print("OK")
